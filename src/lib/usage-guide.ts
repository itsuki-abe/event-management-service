export function organizerSteps(eventId: number | null): GuideStep[] {
	return [
		...(!eventId
			? [
					{
						id: "event",
						title: "イベントを作成する",
						summary: "最初にイベント名を決めましょう。",
						steps: [
							"「LT進行を開く」を押します。",
							"「イベントを作成」にイベント名を入力し、「作成」を押します。",
							"作成後は、画面上部の「使い方」からこのガイドに戻れます。",
						],
						result: "参加登録と会場案内の準備を始められます。",
						link: { href: "/admin", label: "LT進行を開く" },
					},
				]
			: []),
		...(eventId
			? [
					{
						id: "venue",
						title: "会場案内を入力して公開する",
						summary: "受付前に、Wi-Fiやトイレの場所を参加者に届けましょう。",
						steps: [
							"「会場案内を設定する」を押し、項目メニューからWi-Fi・トイレ・入退館などを選びます。",
							"見出しと内容を入力し、「参加者に公開する」をオンにします。Wi-FiはSSIDとパスワードを入力します。",
							"「変更を保存」を押し、「参加者画面を開く」で表示を確認します。",
						],
						result:
							"保存した情報が、参加者の「会場」に表示されます。重要なお知らせはホームにも出ます。",
						link: {
							href: `/admin/guide?eventId=${eventId}`,
							label: "会場案内を設定する",
						},
						note: "住所やアクセス方法は「入退館」や「その他」に記載できます。空欄・非表示の項目は公開されません。会場を別途登録する操作はありません。",
					},
					{
						id: "reception",
						title: "参加用QRで受付を始める",
						summary: "参加者には、スマホで名前を登録してもらいます。",
						steps: [
							"「参加用QRを開く」を押し、受付やスクリーンに掲示します。",
							"参加者にスマホでQRを読み取り、表示名を登録してもらいます。",
							"発表者にも参加登録を済ませてもらいます。運営自身が参加者として使う場合も、別途参加登録します。",
						],
						result: "参加登録した人を、発表の登録時に発表者として選べます。",
						link: {
							href: `/events/${eventId}/qr`,
							label: "参加用QRを開く",
							newTab: true,
						},
						note: "受付で共有するのは参加用QRです。運営用リンクは運営チーム内で利用してください。",
					},
					{
						id: "talks",
						title: "発表を登録し、順番を整える",
						summary: "タイトル・発表者・持ち時間を、発表ごとに設定します。",
						steps: [
							"「LT進行を開く」から「発表を追加」を開きます。",
							"タイトルを入力し、登録済みの発表者を選び、持ち時間（例：5、3:30）を入力して「追加」を押します。",
							"一覧の上下の矢印で発表順を整えます。開始前の発表は鉛筆アイコンから編集できます。",
						],
						result:
							"参加者画面・発表者画面・会場スクリーンに発表情報が共有されます。",
						link: { href: "/admin", label: "LT進行を開く" },
						note: "発表者が選択肢に出ない場合は、同じイベントへの参加登録を確認してください。",
					},
					{
						id: "projection",
						title: "会場スクリーンと画面共有を準備する",
						summary: "会場の投影用PCと、発表者のPCを用意します。",
						steps: [
							"会場の投影用PCで「会場スクリーンを開く」を押し、プロジェクターなどに表示します。",
							"発表者は登録済みの自分のPCで「発表者」画面を開き、「画面共有を準備する」から共有する画面を選びます。",
							"運営は「LT進行」で対象の発表を選び、会場スクリーンに共有画面が映ることを確認します。",
						],
						result:
							"選択中の発表者の画面が投影されます。投影の準備ができてからタイマーを開始します。",
						link: {
							href: "/screen",
							label: "会場スクリーンを開く",
							newTab: true,
						},
						note: "発表者本人による画面選択とブラウザーの許可が必要です。本番前に実際の会場ネットワークで確認してください。",
					},
					{
						id: "progress",
						title: "タイマーを動かし、次の発表へ進む",
						summary: "発表を選ぶ → 投影を確認 → タイマー開始、の順番です。",
						steps: [
							"「LT進行」で発表を選び、準備ができたら「タイマー開始」を押します。",
							"中断時は「一時停止」、続けるときは「再開」を押します。時間を超えても自動では終了しません。",
							"「次の発表へ」で現在の発表を終了して次を選びます。次の発表の準備を確認して、あらためて「タイマー開始」を押します。最後は「発表を終了」を押します。",
						],
						result: "進行状態と残り時間が、各画面に反映されます。",
						link: { href: "/admin", label: "発表の進行を開く" },
					},
					{
						id: "comments",
						title: "コメントの受付と表示を管理する",
						summary:
							"必要に応じて受付を止めたり、投稿を非表示にしたりできます。",
						steps: [
							"「コメント管理を開く」を押します。",
							"「コメント受付」のスイッチで、参加者からの投稿を受け付けるか切り替えます。",
							"対象の発表とコメントを確認し、必要な投稿を非表示にします。",
						],
						result: "参加者のコメント一覧と受付状態に変更が反映されます。",
						link: {
							href: `/admin/comments?eventId=${eventId}`,
							label: "コメント管理を開く",
						},
						note: "「会場投影を許可」は設定の保存までです。コメントを会場スクリーンに表示する機能はまだありません。",
					},
				]
			: []),
	];
}
